// Generates every tool-specific AI entry point from the canonical, tool-neutral skills in
// .agents/skills/<name>/SKILL.md, so a workflow is written once and every assistant sees the same
// list:
//   - .claude/skills/<name>/SKILL.md     Claude Code (/name)
//   - .claude/agents/<name>.md           Claude Code subagents, for skills in CLAUDE_SUBAGENTS
//   - .github/prompts/<name>.prompt.md   GitHub Copilot (/name)
//   - AGENTS.md skill index              Codex, Gemini (via GEMINI.md) and any AGENTS.md-aware tool
// Codex discovers .agents/skills natively, so it needs nothing generated.
//
// Every generated file carries GENERATED_MARKER; files without it are never touched, and generated
// files whose skill no longer exists are deleted.
//
//   node scripts/sync-ai-skills.mjs          write the generated files
//   node scripts/sync-ai-skills.mjs --check  exit 1 if anything is out of date (CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS_DIR = '.agents/skills';
const CLAUDE_SKILLS_DIR = '.claude/skills';
const CLAUDE_AGENTS_DIR = '.claude/agents';
const COPILOT_PROMPTS_DIR = '.github/prompts';
const AGENTS_MD = 'AGENTS.md';
const INDEX_START = '<!-- skills:start -->';
const INDEX_END = '<!-- skills:end -->';
const GENERATED_MARKER = 'Generated by scripts/sync-ai-skills.mjs';
const MARKER_LINE = `<!-- ${GENERATED_MARKER} from the canonical skill. Do not edit; run \`npm run ai:skills:sync\`. -->`;

// Reviewers worth running in an isolated Claude subagent (fresh context, restricted tools) so the
// review is independent of the session that wrote the code. Other tools run the skill inline.
const CLAUDE_SUBAGENTS = {
  'pom-reviewer': 'Read, Grep, Glob, Bash',
  'a11y-reviewer': 'Read, Grep, Glob, Bash',
};

// Agent Skills spec limits: https://agentskills.io/specification
const NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const MAX_DESCRIPTION_LENGTH = 1024;

const check = process.argv.includes('--check');

function readSkills() {
  const dirs = fs
    .readdirSync(path.join(ROOT, SKILLS_DIR), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  return dirs.map((dir) => {
    const file = `${SKILLS_DIR}/${dir}/SKILL.md`;
    const content = fs.readFileSync(path.join(ROOT, file), 'utf8').replaceAll('\r\n', '\n');
    const frontmatter = content.match(/^---\n([\s\S]*?)\n---\n/)?.[1];
    if (!frontmatter) throw new Error(`${file}: missing YAML frontmatter`);

    // Only single-line `name:` / `description:` scalars are used, which keeps this dependency-free.
    const field = (key) =>
      frontmatter
        .match(new RegExp(String.raw`^${key}:[ \t]*(.+)$`, 'm'))?.[1]
        .trim()
        .replace(/^(['"])(.*)\1$/, '$2');
    const name = field('name');
    const description = field('description');

    if (name !== dir) throw new Error(`${file}: name "${name}" must match its folder "${dir}"`);
    if (!NAME_PATTERN.test(name)) throw new Error(`${file}: name must be lowercase kebab-case`);
    if (!description) throw new Error(`${file}: missing description`);
    if (description.length > MAX_DESCRIPTION_LENGTH) {
      throw new Error(`${file}: description exceeds ${MAX_DESCRIPTION_LENGTH} characters`);
    }
    return { name, description, file };
  });
}

// Descriptions are quoted in generated frontmatter so characters like `: ` or `#` in the canonical
// text can never produce invalid YAML. The quote choice mirrors Prettier's (singleQuote: true,
// unless that needs more escapes), so lint-staged doesn't rewrite the output and break --check.
function yamlString(value) {
  const singles = (value.match(/'/g) ?? []).length;
  const doubles = (value.match(/"/g) ?? []).length;
  return singles > doubles ? JSON.stringify(value) : `'${value.replaceAll("'", "''")}'`;
}

function claudeSkill({ name, description, file }) {
  return `---
name: ${name}
description: ${yamlString(description)}
---

${MARKER_LINE}

Read \`${file}\` completely and follow it. Relative paths in that file resolve from
\`${SKILLS_DIR}/${name}/\`.

$ARGUMENTS
`;
}

function claudeAgent({ name, description, file }) {
  return `---
name: ${name}
description: ${yamlString(description)}
tools: ${CLAUDE_SUBAGENTS[name]}
---

${MARKER_LINE}

Read \`${file}\` completely and follow it for the files or diff you were given.
`;
}

function copilotPrompt({ name, description, file }) {
  return `---
description: ${yamlString(description)}
mode: agent
---

${MARKER_LINE}

Read [the \`${name}\` skill](../../${file}) completely and follow it, applied to the input supplied
with this prompt.
`;
}

// First sentence only, so the index stays scannable; the full description lives in the skill.
function summary(description) {
  return description.split(/(?<=\.)\s+(?=[A-Z])/)[0];
}

function agentsMd(skills) {
  const current = fs.readFileSync(path.join(ROOT, AGENTS_MD), 'utf8').replaceAll('\r\n', '\n');
  const start = current.indexOf(INDEX_START);
  const end = current.indexOf(INDEX_END);
  if (start === -1 || end === -1) {
    throw new Error(`${AGENTS_MD}: missing ${INDEX_START} / ${INDEX_END} markers`);
  }
  const list = skills
    .map(({ name, description, file }) => `- [\`${name}\`](${file}) — ${summary(description)}`)
    .join('\n');
  return `${current.slice(0, start)}${INDEX_START}\n\n${list}\n\n${current.slice(end)}`;
}

function expectedFiles(skills) {
  const files = new Map();
  for (const skill of skills) {
    files.set(`${CLAUDE_SKILLS_DIR}/${skill.name}/SKILL.md`, claudeSkill(skill));
    files.set(`${COPILOT_PROMPTS_DIR}/${skill.name}.prompt.md`, copilotPrompt(skill));
    if (CLAUDE_SUBAGENTS[skill.name]) {
      files.set(`${CLAUDE_AGENTS_DIR}/${skill.name}.md`, claudeAgent(skill));
    }
  }
  for (const name of Object.keys(CLAUDE_SUBAGENTS)) {
    if (!skills.some((skill) => skill.name === name)) {
      throw new Error(
        `CLAUDE_SUBAGENTS lists "${name}", which has no ${SKILLS_DIR}/${name}/SKILL.md`
      );
    }
  }
  files.set(AGENTS_MD, agentsMd(skills));
  return files;
}

function existingGeneratedFiles() {
  const found = [];
  const walk = (dir) => {
    const abs = path.join(ROOT, dir);
    if (!fs.existsSync(abs)) return;
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      const rel = `${dir}/${entry.name}`;
      if (entry.isDirectory()) walk(rel);
      else if (fs.readFileSync(path.join(ROOT, rel), 'utf8').includes(GENERATED_MARKER)) {
        found.push(rel);
      }
    }
  };
  [CLAUDE_SKILLS_DIR, CLAUDE_AGENTS_DIR, COPILOT_PROMPTS_DIR].forEach(walk);
  return found;
}

const expected = expectedFiles(readSkills());
const stale = existingGeneratedFiles().filter((file) => !expected.has(file));
const outdated = [...expected].filter(([file, content]) => {
  const abs = path.join(ROOT, file);
  return !fs.existsSync(abs) || fs.readFileSync(abs, 'utf8').replaceAll('\r\n', '\n') !== content;
});

if (check) {
  if (outdated.length === 0 && stale.length === 0) {
    console.log(`AI skill entry points are in sync with ${SKILLS_DIR}.`);
    process.exit(0);
  }
  outdated.forEach(([file]) => console.error(`out of date: ${file}`));
  stale.forEach((file) => console.error(`stale: ${file}`));
  console.error('Run `npm run ai:skills:sync` and commit the result.');
  process.exit(1);
}

for (const [file, content] of outdated) {
  fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, file), content);
  console.log(`wrote ${file}`);
}
for (const file of stale) {
  fs.rmSync(path.join(ROOT, file));
  const dir = path.dirname(path.join(ROOT, file));
  if (fs.readdirSync(dir).length === 0) fs.rmdirSync(dir);
  console.log(`removed ${file}`);
}
if (outdated.length === 0 && stale.length === 0) console.log('Nothing to update.');
